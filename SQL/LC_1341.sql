WITH MOST_MOVIE_REVIEWER AS (
    SELECT
        NAME,
        COUNT(RATING) AS 'CNT'
    FROM USERS U
    JOIN MOVIERATING M
    ON U.USER_ID = M.USER_ID
    GROUP BY U.USER_ID
    ORDER BY CNT DESC, NAME
    LIMIT 1
),

BEST_MOVIE AS (
    SELECT 
        TITLE,
        AVG(RATING) AS 'AVG_RATING'
    FROM MOVIERATING M1
    JOIN MOVIES M2
    ON M1.MOVIE_ID = M2.MOVIE_ID
    WHERE M1.CREATED_AT >= '2020-02-01'
    AND M1.CREATED_AT < '2020-03-01'
    GROUP BY M2.TITLE
    ORDER BY AVG_RATING DESC, M2.TITLE
    LIMIT 1
)


SELECT 
    NAME AS RESULTS
FROM MOST_MOVIE_REVIEWER

UNION ALL

SELECT
    TITLE
FROM BEST_MOVIE


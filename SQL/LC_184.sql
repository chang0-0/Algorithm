
# 문제 : 각 부서별 , 가장 높은 급여를 받는 직원들을 조회하라

WITH TEMP_MAX_SAL AS (
    SELECT D.ID, D.NAME, MAX(SALARY) AS MAX_SALARY
    FROM EMPLOYEE E
    JOIN DEPARTMENT D
    ON E.DEPARTMENTID = D.ID
    GROUP BY D.ID
)


SELECT
    T.NAME AS DEPARTMENT,
    E.NAME AS EMPLOYEE, 
    E.SALARY AS SALARY
FROM TEMP_MAX_SAL T
JOIN EMPLOYEE E
ON T.ID = E.DEPARTMENTID
WHERE E.SALARY = T.MAX_SALARY


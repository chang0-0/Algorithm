

WITH TEMP_GRADE AS (
    SELECT
        S.ID,
        S.MARKS,
        S.NAME,
        G.GRADE AS STUDENT_GRADE
    FROM STUDENTS S
    JOIN GRADES G
        ON S.MARKS >= G.MIN_MARK
        AND S.MARKS <= G.MAX_MARK
),

TEMP_GRADE2 AS (
SELECT 
    ID,
    MARKS,
    NAME,
    CASE
        WHEN STUDENT_GRADE < 8 THEN NULL
        ELSE NAME
    END AS 'STUDENT_NAME',
    STUDENT_GRADE
FROM TEMP_GRADE
)

SELECT 
    STUDENT_NAME,
    STUDENT_GRADE,
    MARKS
FROM TEMP_GRADE2
ORDER BY
    STUDENT_GRADE DESC,
    CASE
        WHEN STUDENT_GRADE >= 8 THEN STUDENT_NAME
    END,
    CASE
        WHEN STUDENT_GRADE < 8 THEN MARKS
    END;


